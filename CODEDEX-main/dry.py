# List with one element
T = [1]

# Using print() to display a message
print("Used Previously")  # Displays the message

# Get the length of the list
print("Length of list:", len(T))
# Show documentation for len()
help(len)

# Get the maximum element in the list
print("Maximum element:", max(T))
# Show documentation for max()
help(max)

# Get the minimum element in the list
print("Minimum element:", min(T))
# Show documentation for min()
help(min)

# Use a new built-in function: sorted(), which returns a sorted list
sorted_list = sorted(T)
print("Sorted list:", sorted_list)
# Show documentation for sorted()
help(sorted)

